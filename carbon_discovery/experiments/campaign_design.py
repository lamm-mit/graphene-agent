"""Campaign design: generates batch specifications for the autonomous discovery study.

Stage 1  baselines (pristine, defected, precracked, hole, reference nanomesh)
Stage 2  broad reconnaissance of the image-derived design variables at matched porosity
(later stages are generated by campaign_stage4.py etc. from the results of earlier stages)

Porosity matching: for every family the free size parameter is adjusted by bisection so that the
relaxed-structure porosity hits the target within +-0.01 (controlled comparison: same carbon mass
per footprint across architectures).
"""
from __future__ import annotations
import sys, os, json, math
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
import numpy as np
from atomistics.structures import design_space as D

AQS = {"d_strain": 0.005, "d_strain_elastic": 0.01, "d_strain_min": 0.00125, "max_strain": 0.32, "fmax": 0.02, "max_steps": 220, "max_fire_steps": 2000, "stop_stress_fraction": 0.10, "post_peak_strain_limit": 0.12}


def porosity_of(family, params):
    a = D.generate(family, **params)
    return a.info["porosity"], len(a)


def match(family, params, target, key, lo, hi, increasing=True, tol=0.008, it=18):
    """bisection on params[key] in [lo,hi] so that porosity ~ target. increasing: porosity grows with key."""
    p = dict(params)
    for _ in range(it):
        mid = 0.5 * (lo + hi)
        p[key] = mid
        phi, n = porosity_of(family, p)
        if abs(phi - target) < tol:
            break
        if (phi < target) == increasing:
            lo = mid
        else:
            hi = mid
    p[key] = round(p[key], 3)
    phi, n = porosity_of(family, p)
    return p, phi, n


def spec(campaign, stage, batch_name, structures, aqs=AQS):
    return {"campaign": campaign, "stage": stage, "batch_name": batch_name, "device": "mps", "dtype": "float32", "aqs": aqs, "structures": structures}


def S(name, family, params, seed=0, reason="", hypothesis="", tags=None, parent=None, prediction=None, notes=None):
    return {"name": name, "family": family, "params": params, "seed": seed, "reason": reason, "hypothesis": hypothesis,
            "tags": tags or [], "parent": parent, "prediction": prediction, "notes": notes}


def write_specs(stage_dir, batches):
    os.makedirs(stage_dir, exist_ok=True)
    for b in batches:
        json.dump(b, open(os.path.join(stage_dir, b["batch_name"] + ".json"), "w"), indent=1)


def stage1():
    L = 100
    st = []
    st.append(S("S1_pristine_zz", "pristine", {"Lx": L, "Ly": L, "orientation": "zigzag"}, reason="baseline: pristine graphene, zigzag along load", tags=["baseline"]))
    st.append(S("S1_pristine_ac", "pristine", {"Lx": L, "Ly": L, "orientation": "armchair"}, reason="baseline: pristine graphene, armchair along load", tags=["baseline"]))
    st.append(S("S1_vac_random_2pct", "vacancies", {"Lx": L, "Ly": L, "fraction": 0.02, "organisation": "random"}, seed=1, reason="baseline: distributed vacancies (2%)", tags=["baseline", "defects"]))
    st.append(S("S1_vac_clustered_2pct", "vacancies", {"Lx": L, "Ly": L, "fraction": 0.02, "organisation": "clustered", "cluster_size": 6}, seed=1, reason="baseline: clustered vacancies (2%, same density)", tags=["baseline", "defects"]))
    for cl in [10, 20, 30]:
        st.append(S(f"S1_precrack_L{cl}", "precrack", {"Lx": L, "Ly": L, "crack_len": cl, "crack_w": 3.0, "angle_deg": 90}, reason=f"baseline: central slit crack {cl} A perpendicular to load (flaw sensitivity)", tags=["baseline", "flaw"]))
    st.append(S("S1_hole_d20", "ring_around_hole", {"Lx": L, "Ly": L, "hole_d": 20, "n_rings": 0}, reason="baseline: circular hole 20 A (blunt flaw)", tags=["baseline", "flaw"]))
    st.append(S("S1_mesh_p16_phi0.2", "nanomesh_single", {"Lx": L, "Ly": L, "pore_d": 8.0, "period": 16}, reason="baseline: reference single-scale nanomesh (period 16, phi~0.2)", tags=["baseline", "mesh"]))
    batches = [spec("discovery", "stage1_baselines", f"stage1_b{k}", st[3 * k:3 * k + 3]) for k in range(3)]
    return batches


def stage2():
    L = 100; LH = 120; phi = 0.20
    st = []
    # (a) hierarchy ladder at matched porosity (cell 120)
    p, f, n = match("nanomesh_single", {"Lx": LH, "Ly": LH, "period": 16}, phi, "pore_d", 3, 14); st.append(S("S2_H1_p16", "nanomesh_single", p, reason="hierarchy ladder: single scale, period 16", hypothesis="exploratory", tags=["hierarchy", "H1"], notes=f"phi={f:.3f}"))
    p, f, n = match("nanomesh_single", {"Lx": LH, "Ly": LH, "period": 32}, phi, "pore_d", 6, 28); st.append(S("S2_H1_p32", "nanomesh_single", p, reason="hierarchy ladder: single coarse scale, period 32", tags=["hierarchy", "H1"], notes=f"phi={f:.3f}"))
    p, f, n = match("nanomesh_single", {"Lx": LH, "Ly": LH, "period": 12}, phi, "pore_d", 3, 10); st.append(S("S2_H1_p12", "nanomesh_single", p, reason="hierarchy ladder: single fine scale, period 12", tags=["hierarchy", "H1"], notes=f"phi={f:.3f}"))
    p, f, n = match("nanomesh_single", {"Lx": LH, "Ly": LH, "period": 40, "shape": "square", "stagger": False}, phi, "pore_d", 5, 36); st.append(S("S2_H1_square_D40", "nanomesh_single", p, reason="hierarchy ladder: coarse level alone (square pores on the 40 A vein grid, no fine pores)", tags=["hierarchy", "H1"], notes=f"phi={f:.3f}"))
    for D2, W2, tag in [(40, 8, "H2_D40_W8"), (24, 8, "H2_D24_W8"), (60, 8, "H2_D60_W8"), (40, 4, "H2_D40_W4"), (40, 12, "H2_D40_W12")]:
        p, f, n = match("nanomesh_hier", {"Lx": LH, "Ly": LH, "levels": 2, "period": 12, "domain": D2, "vein_w": W2}, phi, "pore_d", 3, 11)
        st.append(S(f"S2_{tag}", "nanomesh_hier", p, reason=f"hierarchy ladder: two-level, domain {D2} A (scale ratio {D2/12:.1f}), vein width {W2} A", tags=["hierarchy", "H2"], notes=f"phi={f:.3f}"))
    p, f, n = match("nanomesh_hier", {"Lx": LH, "Ly": LH, "levels": 3, "period": 10, "domain": 30, "vein_w": 5, "level3_domain": 120, "level3_vein": 12}, phi, "pore_d", 3, 9)
    st.append(S("S2_H3_D30_120", "nanomesh_hier", p, reason="hierarchy ladder: three-level (period 10 / domain 30 vein 5 / domain 120 vein 12)", tags=["hierarchy", "H3"], notes=f"phi={f:.3f}"))
    # (b) disorder
    for jit in [1.0, 2.0, 3.0]:
        p, f, n = match("nanomesh_single", {"Lx": L, "Ly": L, "period": 16, "jitter": jit, "seed": 1}, phi, "pore_d", 3, 14)
        st.append(S(f"S2_mesh_jitter{jit}", "nanomesh_single", p, seed=1, reason=f"disorder: pore position jitter {jit} A", tags=["disorder"], notes=f"phi={f:.3f}"))
    for sd in [0.15, 0.3]:
        p, f, n = match("nanomesh_single", {"Lx": L, "Ly": L, "period": 16, "size_disorder": sd, "seed": 1}, phi, "pore_d", 3, 14)
        st.append(S(f"S2_mesh_sizedis{sd}", "nanomesh_single", p, seed=1, reason=f"disorder: pore size dispersion {sd}", tags=["disorder"], notes=f"phi={f:.3f}"))
    for nc, reg in [(25, 0.0), (25, 0.6), (25, 1.0), (50, 0.0)]:
        p, f, n = match("voronoi_network", {"Lx": L, "Ly": L, "n_cells": nc, "regularity": reg, "seed": 1}, phi, "ligament_w", 2, 20, increasing=False)
        st.append(S(f"S2_voronoi_n{nc}_reg{reg}", "voronoi_network", p, seed=1, reason=f"disordered polygonal network: {nc} cells, regularity {reg}", tags=["disorder", "network"], notes=f"phi={f:.3f}"))
    # (c) anisotropy / load path
    for ang in [0, 45, 90]:
        p, f, n = match("slit_array", {"Lx": L, "Ly": L, "slit_w": 4.0, "period_x": 30, "period_y": 16, "angle_deg": ang}, phi, "slit_len", 4, 28)
        st.append(S(f"S2_slit_{ang}deg", "slit_array", p, reason=f"anisotropy: slit pores at {ang} deg to the load", tags=["anisotropy"], notes=f"phi={f:.3f}"))
    for ang in [0, 90]:
        p, f, n = match("nanomesh_single", {"Lx": L, "Ly": L, "period": 16, "aspect": 2.0, "angle_deg": ang}, phi, "pore_d", 3, 14)
        st.append(S(f"S2_ellipse_{ang}deg", "nanomesh_single", p, reason=f"anisotropy: elliptical pores (aspect 2) long axis at {ang} deg", tags=["anisotropy"], notes=f"phi={f:.3f}"))
    for angs, tag in [((0, 60, 120), "060120"), ((0, 90), "090"), ((30, 90, 150), "3090150")]:
        p, f, n = match("strut_lattice", {"Lx": L, "Ly": L, "spacing": 25, "angles_deg": list(angs)}, 0.45, "strut_w", 2, 20, increasing=False)
        st.append(S(f"S2_strut_{tag}", "strut_lattice", p, reason=f"load-path organisation: straight struts at {angs} deg (phi 0.45)", tags=["loadpath", "connectivity"], notes=f"phi={f:.3f}"))
    # (d) porosity sweep (single mesh p16)
    for ph in [0.10, 0.30, 0.40]:
        p, f, n = match("nanomesh_single", {"Lx": L, "Ly": L, "period": 16}, ph, "pore_d", 2, 15)
        st.append(S(f"S2_mesh_phi{ph}", "nanomesh_single", p, reason=f"porosity sweep: single mesh phi={ph}", tags=["porosity"], notes=f"phi={f:.3f}"))
    # (e) gradients / flaw halo
    for mode in ["x", "radial"]:
        p, f, n = match("graded_pores", {"Lx": L, "Ly": L, "period": 16, "pore_d_min": 4.0, "mode": mode}, phi, "pore_d_max", 4, 15)
        st.append(S(f"S2_graded_{mode}", "graded_pores", p, reason=f"gradient: pore size graded ({mode})", tags=["gradient"], notes=f"phi={f:.3f}"))
    st.append(S("S2_hole20_rings2", "ring_around_hole", {"Lx": L, "Ly": L, "hole_d": 20, "n_rings": 2, "ring_pore_d": 5.0, "ring_gap": 8.0}, reason="flaw halo: hole 20 A + 2 rings of 5 A pores", tags=["flaw", "gradient"]))
    a = D.generate("ring_around_hole", Lx=L, Ly=L, hole_d=20, n_rings=2, ring_pore_d=5.0, ring_gap=8.0); ph_halo = a.info["porosity"]
    p, f, n = match("ring_around_hole", {"Lx": L, "Ly": L, "hole_d": 20, "n_rings": 0, "background": {"pore_d": 5.0, "period": 16}}, ph_halo, "background_pore_d_placeholder", 0, 1, it=0) if False else (None, None, None)
    # background pores matched: vary background pore_d manually
    best = None
    for pd in np.arange(2.0, 8.01, 0.25):
        a2 = D.generate("ring_around_hole", Lx=L, Ly=L, hole_d=20, n_rings=0, background={"pore_d": float(pd), "period": 16})
        if best is None or abs(a2.info["porosity"] - ph_halo) < abs(best[1] - ph_halo):
            best = (float(pd), a2.info["porosity"])
    st.append(S("S2_hole20_background", "ring_around_hole", {"Lx": L, "Ly": L, "hole_d": 20, "n_rings": 0, "background": {"pore_d": best[0], "period": 16}}, reason=f"flaw halo control: hole 20 A + uniform far-field pores at the same porosity ({ph_halo:.3f})", tags=["flaw", "gradient"], notes=f"phi={best[1]:.3f}"))
    # (f) defect organisation
    for fr in [0.01, 0.03]:
        for org in ["random", "clustered"]:
            st.append(S(f"S2_vac_{org}_{fr}", "vacancies", {"Lx": L, "Ly": L, "fraction": fr, "organisation": org, "cluster_size": 6}, seed=1, reason=f"defect organisation: {org} vacancies {fr*100:.0f}%", tags=["defects"]))
    # (g) lattice orientation at fixed architecture
    p, f, n = match("nanomesh_single", {"Lx": L, "Ly": L, "period": 16, "orientation": "armchair"}, phi, "pore_d", 3, 14)
    st.append(S("S2_mesh_p16_armchair", "nanomesh_single", p, reason="lattice orientation: reference mesh with armchair along load", tags=["orientation"], notes=f"phi={f:.3f}"))
    # batches of 3-4, grouped by cell size
    big = [s for s in st if s["params"].get("Lx", 100) >= 120]
    small = [s for s in st if s["params"].get("Lx", 100) < 120]
    batches = []
    k = 0
    for group, size in [(big, 3), (small, 4)]:
        for i in range(0, len(group), size):
            batches.append(spec("discovery", "stage2_reconnaissance", f"stage2_b{k:02d}", group[i:i + size])); k += 1
    return batches, st


